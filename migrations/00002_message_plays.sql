-- ЖУРНАЛ ПРОСЛУШИВАНИЙ
--
-- Строка на каждое открытие записи разговора. Не счётчик колонкой в messages:
-- вопрос «кто слушал» без истории не отвечается, а «сколько раз» из истории
-- считается — поэтому счётчик play_count в списке обращений собирается
-- подзапросом отсюда, а не хранится отдельно. Так они не разойдутся.
--
-- Считается именно открытие записи, а не прослушивание: фронт качает mp3 одним
-- запросом и дальше играет из blob, так что повторы и перемотки до сервиса не
-- доезжают. Range-запросы в журнал не попадают — это догрузка хвоста.
--
-- user_name — снепшот на момент открытия. Пользователи живут в базе портала,
-- присоединяться отсюда не к чему, да и для журнала так честнее: сменившаяся
-- фамилия не должна переписывать записи задним числом.
-- ============================================================================

CREATE TABLE message_plays (
    id         INTEGER PRIMARY KEY,
    -- ON DELETE CASCADE, чтобы ручная чистка обращений не оставляла сирот.
    -- Работает только при PRAGMA foreign_keys=ON: сервис ставит её в DSN сам,
    -- а в консоли sqlite3 её нужно писать в той же строке, что и DELETE.
    message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    user_id    INTEGER NOT NULL,           -- из X-User-Id, клейм id в JWT
    user_name  TEXT    NOT NULL DEFAULT '',
    played_at  INTEGER NOT NULL            -- unix seconds, как везде в схеме
);

-- Один индекс на оба запроса: count(*) для play_count берётся прямо из него, до
-- таблицы не доходя, и он же отбирает строки для GET /messages/{id}/plays.
-- Сортировка там идёт по единицам строк на обращение, составной индекс с
-- played_at того не стоит. Индексы на user_id и played_at появятся, если
-- понадобятся срезы «что слушал такой-то» или «всё за период».
CREATE INDEX idx_message_plays_message ON message_plays (message_id);

